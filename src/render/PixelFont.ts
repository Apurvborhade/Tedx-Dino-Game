export class PixelFont {
  /**
   * Draw text at virtual pixel coordinates.
   * @param scale Integer scale multiplier (default 1 = 5x7 px glyphs + 1px spacing)
   */
  static draw(
    ctx: CanvasRenderingContext2D,
    text: string,
    x: number,
    y: number,
    color: string,
    scale = 1
  ): void {
    ctx.fillStyle = color;
    const str = text.toUpperCase();
    let curX = Math.round(x);
    const curY = Math.round(y);
    const charSpacing = scale;

    for (let i = 0; i < str.length; i++) {
      const ch = str[i] ?? ' ';
      const cols = FONT_5X7[ch] ?? FONT_5X7['?']!;

      for (let colIdx = 0; colIdx < 5; colIdx++) {
        const colBits = cols[colIdx] ?? 0;
        for (let rowIdx = 0; rowIdx < 7; rowIdx++) {
          if ((colBits & (1 << rowIdx)) !== 0) {
            ctx.fillRect(
              curX + colIdx * scale,
              curY + rowIdx * scale,
              scale,
              scale
            );
          }
        }
      }

      curX += (5 * scale) + charSpacing;
    }
  }

  /** Measure rendered width of a string at given scale in virtual pixels */
  static measureWidth(text: string, scale = 1): number {
    if (text.length === 0) return 0;
    return text.length * 6 * scale - scale;
  }
}
